function makeSeries(t30Before, t7After, t90After) {
  // Normalized to 100 at T=0 (scandal date)
  const startPrice = +(100 / (1 + t30Before / 100)).toFixed(2);
  const d20 = +(startPrice + (100 - startPrice) * 0.35).toFixed(2);
  const d10 = +(startPrice + (100 - startPrice) * 0.72).toFixed(2);
  const d5 = +(startPrice + (100 - startPrice) * 0.9).toFixed(2);
  const p0 = 100.0;
  const p7 = +(100 + t7After).toFixed(2);
  const p15 = +(100 + t7After * 0.85 + (t90After - t7After) * 0.2).toFixed(2);
  const p30 = +(100 + t7After * 0.6 + (t90After - t7After) * 0.45).toFixed(2);
  const p60 = +(100 + t7After * 0.3 + (t90After - t7After) * 0.75).toFixed(2);
  const p90 = +(100 + t90After).toFixed(2);

  return JSON.stringify([
    { day: 'T-30', stock: startPrice, spy: 98.4 },
    { day: 'T-20', stock: d20, spy: 98.9 },
    { day: 'T-10', stock: d10, spy: 99.5 },
    { day: 'T-5', stock: d5, spy: 99.8 },
    { day: 'T=0', stock: p0, spy: 100.0 },
    { day: 'T+7', stock: p7, spy: 100.4 },
    { day: 'T+15', stock: p15, spy: 100.9 },
    { day: 'T+30', stock: p30, spy: 101.5 },
    { day: 'T+60', stock: p60, spy: 102.6 },
    { day: 'T+90', stock: p90, spy: 103.8 }
  ]);
}

